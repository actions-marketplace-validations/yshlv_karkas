def build_project_tree(project_root: str | Path, max_depth: int = 4) -> str:
    """Generate an annotated ASCII file and folder structure tree for the codebase."""
    root = Path(project_root).resolve()
    lines: list[str] = [f"📁 {root.name}/"]

    def _walk(dir_path: Path, prefix: str = "", depth: int = 1) -> None:
        if depth > max_depth:
            return

        try:
            entries = sorted(
                dir_path.iterdir(),
                key=lambda e: (0 if e.is_dir() else 1, e.name.lower()),
            )
        except (PermissionError, OSError):
            return

        # Filter out ignored files and hidden folders
        filtered: list[Path] = [
            e for e in entries
            if e.name not in IGNORED_NAMES and not e.name.startswith(".git")
        ]

        total = len(filtered)
        for idx, entry in enumerate(filtered):
            is_last = (idx == total - 1)
            connector = "└── " if is_last else "├── "
            child_prefix = prefix + ("    " if is_last else "│   ")

            # Calculate relative path from project root
            try:
                rel_path = entry.relative_to(root).as_posix()
            except ValueError:
                rel_path = entry.name

            annotation = ""
            if entry.is_dir():
                # Check directory annotation
                if rel_path in DIRECTORY_ANNOTATIONS:
                    annotation = f" # {DIRECTORY_ANNOTATIONS[rel_path]}"
                elif rel_path.startswith("src/core/use_cases/"):
                    sub = rel_path.split("/")[-1]
                    annotation = f" # Application workflows for {sub} domain"
                elif rel_path.startswith("src/core/services/"):
                    sub = rel_path.split("/")[-1]
                    annotation = f" # Business services for {sub} domain"

                lines.append(f"{prefix}{connector}📁 {entry.name}/{annotation}")
                _walk(entry, child_prefix, depth + 1)
            else:
                # File annotation
                if entry.name in FILE_ANNOTATIONS:
                    annotation = f" # {FILE_ANNOTATIONS[entry.name]}"
                elif rel_path in FILE_ANNOTATIONS:
                    annotation = f" # {FILE_ANNOTATIONS[rel_path]}"

                # Only show files in root or important top-level directories
                if depth <= 2 or entry.name in FILE_ANNOTATIONS:
                    lines.append(f"{prefix}{connector}📄 {entry.name}{annotation}")
                elif is_last and total > 5 and depth >= 3:
                    # Compact representation for deep directories with many files
                    pass

    _walk(root, "", 1)
    return "\n".join(lines)
